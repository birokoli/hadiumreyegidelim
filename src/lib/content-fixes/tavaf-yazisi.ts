const heading = (title: string) => new RegExp(`^#{2,3}\\s*${title.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\s*$`, "m");

/** Yazıya yeni bölümleri ekler. Dönüş: yeni içerik ve atlanan adımlar. Saf fonksiyon (test edilebilir). */
export function applyTavafSections(content: string): { content: string; skipped: string[] } {
  const skipped: string[] = [];
  let c = content;
  if (c.includes("## Tavafa nasıl niyet edilir?")) return { content: c, skipped: ["zaten eklenmiş"] };
  const insertBefore = (title: string, block: string, label: string) => {
    const m = heading(title).exec(c);
    if (!m) { skipped.push(`${label}: "${title}" başlığı yok`); return false; }
    c = c.slice(0, m.index) + block + c.slice(m.index);
    return true;
  };
  if (!insertBefore("Hacerülesved'i istilam ederken ne denir?", NIYET_VE_ADIMLAR, "niyet+adımlar")) {
    // Başlık bulunamazsa ilk H2'nin önüne
    const m = /^##\s/m.exec(c);
    if (m) c = c.slice(0, m.index) + NIYET_VE_ADIMLAR + c.slice(m.index);
  }
  if (!insertBefore("Tavaf namazından sonra hangi dua okunur?", NAMAZ, "namaz")) insertBefore("Tavafa çıkmadan önce neleri kontrol etmeli?", NAMAZ, "namaz (yedek)");
  if (!insertBefore("Tavafa çıkmadan önce neleri kontrol etmeli?", UMRE_DUALARI, "umre duaları")) insertBefore("Kendi programınızla umre nasıl planlanır?", UMRE_DUALARI, "umre duaları (yedek)");
  if (!insertBefore("Kendi programınızla umre nasıl planlanır?", KITAPCIK, "kitapçık")) c = c.trimEnd() + "\n\n" + KITAPCIK;
  return { content: c, skipped };
}
